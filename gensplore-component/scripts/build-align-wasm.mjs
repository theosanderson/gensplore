// Rebuilds src/comparison/nextclade/ from align-wasm/ (needs rustup and wasm-pack).
// The output is committed so installing or building Gensplore never needs Rust.
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { thirdPartyLicenses } from './third-party-licenses.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = join(root, 'src/comparison/nextclade');
const pkg = await mkdtemp(join(tmpdir(), 'gensplore-align-'));
try {
  execFileSync('wasm-pack', ['build', '--release', '--target', 'web', '--no-pack', '--out-dir', pkg, '--out-name', 'align'], { cwd: join(root, 'align-wasm'), stdio: 'inherit' });
  let glue = await readFile(join(pkg, 'align.js'), 'utf8');
  // Only initSync is used, with the embedded bytes. Drop the default loader's
  // fetch of a sibling .wasm URL so bundlers do not look for that file.
  const loader = "module_or_path = new URL('align_bg.wasm', import.meta.url);";
  assert(glue.includes(loader), 'wasm-bindgen loader changed; update build-align-wasm.mjs');
  glue = glue.replace(loader, "throw new Error('Use initSync with the embedded module.');");
  const wasm = await readFile(join(pkg, 'align_bg.wasm'));
  await rm(output, { recursive: true, force: true });
  await mkdir(output, { recursive: true });
  const header = '// Generated by scripts/build-align-wasm.mjs from align-wasm/. Do not edit.\n'
    + '// Compiled from Nextclade (MIT, https://github.com/nextstrain/nextclade) and Rust crates;\n'
    + '// their license notices are in THIRD_PARTY_LICENSES.txt at the package root.\n';
  await writeFile(join(output, 'align.js'), header + glue);
  // Base64 in a module, not a .wasm asset: identical in Node tests, Vite's inline
  // worker and consumers' bundlers, with no asset URL to resolve.
  await writeFile(join(output, 'wasm.js'), `${header}export default '${wasm.toString('base64')}';\n`);
  // Shipped in the npm package beside dist/, which embeds the module.
  await writeFile(join(root, 'THIRD_PARTY_LICENSES.txt'), thirdPartyLicenses(join(root, 'align-wasm')));
  console.log(`Wrote ${output} (${wasm.length} byte module) and THIRD_PARTY_LICENSES.txt`);
} finally {
  await rm(pkg, { recursive: true, force: true });
}
